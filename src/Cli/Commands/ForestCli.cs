using System.CommandLine;
using ContainerForest.Cli.Api;

namespace ContainerForest.Cli.Commands;

/// <summary>The command tree of <c>forest</c>.</summary>
internal static class ForestCli
{
    public static RootCommand Build(CliHost host)
    {
        var root = new RootCommand("forest: the container-forest command line. Sign in with 'forest login <server>'.");
        foreach (var option in GlobalOptions.All)
        {
            root.Add(option);
        }

        ICliNode[] tree =
        [
            new LoginCommand(),
            new LogoutCommand(),
            new WhoAmICommand(),
            new CommandGroup("context", "Saved servers and tokens.",
                new ContextListCommand(),
                new ContextUseCommand(),
                new ContextRemoveCommand(),
                new ContextSetEnvironmentCommand()),
            new CommandGroup("env", "Environments: hosts with an agent.",
                new EnvListCommand(),
                new EnvShowCommand(),
                new EnvCreateCommand(),
                new EnvUpdateCommand(),
                new EnvRemoveCommand(),
                new EnvEnrollmentTokenCommand(),
                new EnvRevokeAgentCommand(),
                new EnvStatsCommand(),
                new CommandGroup("key", "Age keys SOPS files are encrypted for.",
                    new KeyListCommand(),
                    new KeyCreateCommand(),
                    new KeyRemoveCommand()),
                new CommandGroup("registry", "Container registry logins the agent pulls with.",
                    new RegistryListCommand(),
                    new RegistrySetCommand(),
                    new RegistryRemoveCommand()),
                new CommandGroup("policy", "The compose policy: what the stacks' compose files may do on the host (ADR-0012).",
                    new PolicyShowCommand(),
                    new PolicySetCommand(),
                    new PolicyReportCommand()),
                new CommandGroup("role", "Roles on the environment and its stacks, for its administrators.",
                    new EnvRoleListCommand(),
                    new EnvRoleGrantCommand(),
                    new EnvRoleChangeCommand(),
                    new EnvRoleRevokeCommand())),
            new CommandGroup("container", "Containers of an environment.",
                new ContainerListCommand(),
                new ContainerControlCommand(ContainerAction.Start, "Start a container."),
                new ContainerControlCommand(ContainerAction.Stop, "Stop a container."),
                new ContainerControlCommand(ContainerAction.Restart, "Restart a container."),
                new ContainerControlCommand(ContainerAction.Remove, "Remove a stopped container; its volumes stay (Editor)."),
                new ContainerLogsCommand(),
                new ContainerStatsCommand()),
            new CommandGroup("unmanaged", "Unmanaged stacks: compose projects run by hand on the host (ADR-0016).",
                new UnmanagedListCommand(),
                new UnmanagedControlCommand(UnmanagedStackAction.Up, "Bring the stack up (compose up -d, Editor)."),
                new UnmanagedControlCommand(UnmanagedStackAction.Pull, "Pull the stack's images (compose pull, Editor)."),
                new UnmanagedControlCommand(UnmanagedStackAction.Restart, "Restart the stack's containers (compose restart, Operator)."),
                new UnmanagedControlCommand(UnmanagedStackAction.Down, "Stop and remove the stack's containers (compose down, Editor).")),
            new CommandGroup("stack", "Stacks: compose projects deployed from git.",
                new StackListCommand(),
                new StackShowCommand(),
                new StackCreateCommand(),
                new StackSetSourceCommand(),
                new StackRemoveCommand(),
                new StackDeployCommand(),
                new StackControlCommand(StackAction.Restart, "Restart the stack's containers (compose restart, Operator)."),
                new StackControlCommand(StackAction.Down, "Stop and remove the stack's containers (compose down, Editor)."),
                new StackSwitchCommand("deploy-on-push", "Deploy after a push to the branch (Editor).", (api, id, on, ct) => api.SetDeployOnPushAsync(id, on, ct)),
                new StackSwitchCommand("restart-on-file-change", "Restart after a deploy that changed files (Editor).", (api, id, on, ct) => api.SetRestartOnFileChangeAsync(id, on, ct)),
                new StackSwitchCommand("require-signed-commits", "Deploy only commits signed by someone who may deploy the stack (Editor).", (api, id, on, ct) => api.SetRequireSignedCommitsAsync(id, on, ct)),
                new StackSwitchCommand("require-image-digests", "Deploy only images pinned by digest (Editor).", (api, id, on, ct) => api.SetRequireImageDigestsAsync(id, on, ct)),
                new CommandGroup("policy", "The stack's own allowances beyond the environment's compose policy (ADR-0012).",
                    new StackPolicyCommand(allow: true),
                    new StackPolicyCommand(allow: false),
                    new StackSwitchCommand(
                        "unrestricted",
                        "Take the stack out of the compose policy altogether: its Editors are root on the host (administrators of the environment).",
                        (api, id, on, ct) => api.SetPolicyUnrestrictedAsync(id, on, ct))),
                new CommandGroup("hook", "The stack's deploy hook for CI.",
                    new StackHookCreateCommand(),
                    new StackHookRemoveCommand()),
                new CommandGroup("image-policy", "Images the aggregator updates in the stack's compose file (ADR-0015).",
                    new ImagePolicyListCommand(),
                    new ImagePolicyAddCommand(),
                    new ImagePolicyChangeCommand(),
                    new ImagePolicyRemoveCommand(),
                    new ImagePolicyCheckCommand(),
                    new ImagePinCommand(),
                    new ImageUnpinCommand()),
                new CommandGroup("image-hook", "The stack's image hook for CI: check the image policies now or ask for a tag.",
                    new ImageHookCreateCommand(),
                    new ImageHookDowngradeCommand(),
                    new ImageHookRemoveCommand())),
            new CommandGroup("deployment", "Deployments of a stack.",
                new DeploymentListCommand(),
                new DeploymentShowCommand(),
                new DeploymentLogsCommand()),
            new CommandGroup("repo", "Git repositories stacks deploy from.",
                new RepoListCommand(),
                new RepoAddCommand(),
                new RepoUpdateCommand(),
                new RepoRemoveCommand(),
                new CommandGroup("webhook", "The repository's push webhook.",
                    new RepoWebhookCreateCommand(),
                    new RepoWebhookRemoveCommand())),
            new CommandGroup("connection", "Git connections: credentials and environments for a git server's repositories.",
                new ConnectionListCommand(),
                new ConnectionAddCommand(),
                new ConnectionUpdateCommand(),
                new ConnectionRemoveCommand(),
                new ConnectionSetTokenCommand(),
                new ConnectionRemoveTokenCommand(),
                new ConnectionSetPushTokenCommand(),
                new ConnectionRemovePushTokenCommand(),
                new CommandGroup("webhook", "The connection's organization webhook.",
                    new ConnectionWebhookCreateCommand(),
                    new ConnectionWebhookRemoveCommand())),
            new CommandGroup("user", "Users, their roles and API tokens (administrators).",
                new UserListCommand(),
                new UserShowCommand(),
                new UserCreateCommand(),
                new UserRenameCommand(),
                new UserActivationCommand(activate: false),
                new UserActivationCommand(activate: true),
                new UserSetAdminCommand(),
                new UserResetPasswordCommand(),
                new UserUnlockCommand(),
                new CommandGroup("role", "Roles on environments and stacks.",
                    new RoleGrantCommand(),
                    new RoleChangeCommand(),
                    new RoleRevokeCommand()),
                new CommandGroup("token", "The user's API tokens.",
                    new UserTokensCommand(),
                    new UserRevokeTokenCommand()),
                new CommandGroup("passkey", "The user's passkeys.",
                    new UserPasskeysCommand(),
                    new UserRemovePasskeyCommand()),
                new CommandGroup("signing-key", "SSH keys whose commit signatures endorse deployments (ADR-0011).",
                    new UserSigningKeysCommand(),
                    new UserAddSigningKeyCommand(),
                    new UserRemoveSigningKeyCommand())),
            new CommandGroup("secrets", "SOPS secrets in git, decrypted in your clone by the forest filter (ADR-0010).",
                new SecretsInitCommand(),
                new SecretsAdoptCommand(),
                new SecretsAddCommand(),
                new SecretsRemoveCommand(),
                new SecretsStatusCommand(),
                new SecretsCheckCommand(),
                new SecretsUpdateKeysCommand(),
                new SecretsFixEolCommand(),
                new CommandGroup("rule", "The creation rules of .sops.yaml: which environments' keys encrypt which files.",
                    new SecretsRuleListCommand(),
                    new SecretsRuleAddCommand(),
                    new SecretsRuleRemoveCommand())),
            new CommandGroup("git", "The forest git filter.",
                new GitSetupCommand(),
                new GitTeardownCommand(),
                new GitFilterProcessCommand(),
                new GitTextconvCommand()),
            new CommandGroup("system", "The aggregator itself (administrators).",
                new CommandGroup("signing-key", "The key the aggregator signs its image update commits with (ADR-0015).",
                    new SigningKeyShowCommand(),
                    new SigningKeyRotateCommand())),
            new CommandGroup("backup", "The aggregator's backup; its settings are changed in the panel (ADR-0014).",
                new BackupStatusCommand(),
                new BackupRunCommand()),
            new CommandGroup("notification", "Notifications the Discord bot posts (administrators).",
                new CommandGroup("channel", "Discord channels.",
                    new ChannelListCommand(),
                    new ChannelAddCommand(),
                    new ChannelUpdateCommand(),
                    new ChannelRemoveCommand()),
                new CommandGroup("rule", "Which events go to a channel.",
                    new RuleListCommand(),
                    new RuleAddCommand(),
                    new RuleUpdateCommand(),
                    new RuleRemoveCommand()),
                new NotificationHistoryCommand()),
        ];

        foreach (var node in tree)
        {
            root.Add(node.Build(host));
        }

        return root;
    }
}
